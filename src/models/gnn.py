def make_gin_conv(in_ch, out_ch):
    return GINConv(nn.Sequential(
        nn.Linear(in_ch, out_ch), nn.BatchNorm1d(out_ch), nn.ReLU(),
        nn.Linear(out_ch, out_ch), nn.BatchNorm1d(out_ch), nn.ReLU()
    ))


class GINClassification(nn.Module):
    def __init__(self, in_channels, hidden_channels, out_channels, num_classes):
        super().__init__()
        self.conv1 = make_gin_conv(in_channels,    hidden_channels)
        self.conv2 = make_gin_conv(hidden_channels, hidden_channels)
        self.conv3 = make_gin_conv(hidden_channels, out_channels)
        self.classifier = nn.Linear(out_channels, num_classes)

    def forward(self, x, edge_index, batch):
        x = self.conv1(x, edge_index)
        x = self.conv2(x, edge_index)
        x = self.conv3(x, edge_index)
        x = global_mean_pool(x, batch)
        return self.classifier(x)

    def extract_embedding(self, x, edge_index, batch):
        x = self.conv1(x, edge_index)
        x = self.conv2(x, edge_index)
        x = self.conv3(x, edge_index)
        return global_mean_pool(x, batch)

